let current = "fr";
const listeners = new Set();

export function detectLanguage() {
  const stored = getPref("lang");
  if (stored === "fr" || stored === "en") return stored;
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "fr";
  return String(nav).toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function getLanguage() { return current; }
export function setLanguage(lang, { persist = true } = {}) {
  if (lang !== "fr" && lang !== "en") return;
  current = lang;
  if (persist) setPref("lang", lang);
  document.documentElement.lang = lang;
  for (const cb of listeners) cb(lang);
}
export function onLanguage(cb) { listeners.add(cb); return () => listeners.delete(cb); }

export function t(key, vars) {
  let text = (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.fr[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll("{" + name + "}", String(value));
  return text;
}

// Pick the current-language value out of a {fr, en} object (falls back to fr, then any string).
export function L(value) {
  if (value == null) return "";
  if (typeof value === "string") return value;
  return value[current] ?? value.fr ?? value.en ?? "";
}

// Apply [data-i18n], [data-i18n-aria], [data-i18n-placeholder], [data-i18n-title] attributes inside a root.
export function applyTranslations(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.setAttribute("title", t(el.dataset.i18nTitle));
}
